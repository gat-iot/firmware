"""Build a bounded, font-compatible prediction subset from the existing dictionary."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/graphics/pinyin_trie_static.h"
OUTPUT = ROOT / "src/graphics/gat562_pinyin_predictions.h"


def numbers(source, name):
    match = re.search(r"\b" + name + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise ValueError(name)
    return [int(value) for value in re.findall(r"\d+", match[1])]


def build():
    source = SOURCE.read_text(encoding="utf-8")
    pool = bytes(numbers(source, "WORDS_DATA"))
    offsets = numbers(source, "WORDS_OFFSETS")
    weights = numbers(source, "WORDS_WEIGHT")
    font = (ROOT / "variants/nrf52840/gat562_mesh_trial_tracker/gat562_utf8_10x10.h").read_text()
    font_map = font.split("PROGMEM = {", 1)[1].split("};", 1)[0]
    supported = {int(code, 16) for code in re.findall(r"0x[0-9A-Fa-f]+", font_map)}
    words = {}
    for offset, weight in zip(offsets, weights):
        word = pool[offset:pool.index(0, offset)].decode("utf-8")
        if 2 <= len(word) <= 4 and all(0x4E00 <= ord(c) <= 0x9FFF and ord(c) in supported for c in word):
            words[word] = max(weight, words.get(word, 0))
    selected = []
    counts = {}
    size = 0
    for word in sorted(words, key=lambda w: (-words[w], w)):
        if counts.get(word[0], 0) >= 16:
            continue
        cost = len(word.encode("utf-8")) + 1
        if size + cost > 40000:
            continue
        selected.append(word)
        counts[word[0]] = counts.get(word[0], 0) + 1
        size += cost
    selected.sort(key=lambda w: (w[0], -words[w], w))
    lines = [
        "#pragma once",
        "// Generated by bin/generate-gat562-predictions.py; do not edit by hand.",
        "// Subset of pinyin_trie_static.h; original attribution retained below.",
        source[:source.index("*/") + 2],
        "static const char gat562PinyinPredictions[] =",
    ]
    for word in selected:
        escaped = "".join(f"\\x{byte:02x}" for byte in word.encode("utf-8"))
        lines.append(f'    "{escaped}\\0"')
    lines[-1] += ";"
    return "\n".join(lines) + "\n", selected


if __name__ == "__main__":
    import sys
    content, words = build()
    if "--check" in sys.argv:
        assert OUTPUT.read_text(encoding="utf-8") == content
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print(f"{len(words)} prediction words; {len({w[0] for w in words})} leading characters")
